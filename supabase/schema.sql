-- =========================================================
-- MODUL TRANSAKSI, INVOICE, DAN LAPORAN BULANAN
-- Jalankan setelah schema utama. Semua tabel hanya dapat
-- dikelola oleh akun yang terdaftar di florist_admins.
-- =========================================================

create sequence if not exists public.florist_invoice_number_seq start 1;

create table if not exists public.florist_orders (
  id bigint generated by default as identity primary key,
  invoice_number text not null unique default (
    'FD-' || to_char(now(), 'YYYYMM') || '-' ||
    lpad(nextval('public.florist_invoice_number_seq')::text, 5, '0')
  ),
  customer_name text not null,
  customer_phone text default '',
  customer_address text default '',
  source_website text not null default 'Fingerdance Florist',
  order_date date not null default current_date,
  subtotal numeric(14,2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(14,2) not null default 0 check (delivery_fee >= 0),
  discount numeric(14,2) not null default 0 check (discount >= 0),
  total numeric(14,2) not null default 0 check (total >= 0),
  payment_status text not null default 'Belum dibayar'
    check (payment_status in ('Belum dibayar','DP','Lunas','Dibatalkan')),
  order_status text not null default 'Menunggu'
    check (order_status in ('Menunggu','Diproses','Siap dikirim','Selesai','Dibatalkan')),
  notes text default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.florist_orders add column if not exists amount_paid numeric(14,2) not null default 0 check (amount_paid >= 0);

create table if not exists public.florist_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.florist_orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  line_total numeric(14,2) not null default 0 check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists florist_orders_order_date_idx on public.florist_orders(order_date desc);
create index if not exists florist_orders_payment_status_idx on public.florist_orders(payment_status);
create index if not exists florist_orders_source_idx on public.florist_orders(source_website);
create index if not exists florist_order_items_order_id_idx on public.florist_order_items(order_id);

alter table public.florist_orders enable row level security;
alter table public.florist_order_items enable row level security;

drop policy if exists "Admins manage florist orders" on public.florist_orders;
create policy "Admins manage florist orders" on public.florist_orders
  for all to authenticated
  using (public.is_florist_admin())
  with check (public.is_florist_admin());

drop policy if exists "Admins manage florist order items" on public.florist_order_items;
create policy "Admins manage florist order items" on public.florist_order_items
  for all to authenticated
  using (public.is_florist_admin())
  with check (public.is_florist_admin());

create or replace function public.set_florist_order_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists florist_orders_updated_at on public.florist_orders;
create trigger florist_orders_updated_at
before update on public.florist_orders
for each row execute function public.set_florist_order_updated_at();

grant usage, select on sequence public.florist_invoice_number_seq to authenticated;
