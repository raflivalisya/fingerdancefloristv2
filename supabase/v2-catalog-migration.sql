-- FINGER DANCE FLORIST V2
-- Jalankan satu kali di Supabase SQL Editor pada project/database yang sama
-- dengan website V1. Tidak mengubah atau menghapus katalog V1.

create table if not exists public.florist_v2_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text default '✿',
  description text default '',
  sort_order integer not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.florist_v2_products (
  id bigint generated by default as identity primary key,
  category text not null,
  subcategory text default '',
  name text not null,
  image text default '',
  price numeric(14,2),
  description text default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists florist_v2_products_category_idx
  on public.florist_v2_products (category);
create index if not exists florist_v2_products_active_idx
  on public.florist_v2_products (is_active);

alter table public.florist_v2_categories enable row level security;
alter table public.florist_v2_products enable row level security;

drop policy if exists "Public can read active V2 categories" on public.florist_v2_categories;
create policy "Public can read active V2 categories"
  on public.florist_v2_categories for select
  using (is_active = true or public.is_florist_admin());

drop policy if exists "Admins manage V2 categories" on public.florist_v2_categories;
create policy "Admins manage V2 categories"
  on public.florist_v2_categories for all to authenticated
  using (public.is_florist_admin())
  with check (public.is_florist_admin());

drop policy if exists "Public can read active V2 products" on public.florist_v2_products;
create policy "Public can read active V2 products"
  on public.florist_v2_products for select
  using (is_active = true or public.is_florist_admin());

drop policy if exists "Admins manage V2 products" on public.florist_v2_products;
create policy "Admins manage V2 products"
  on public.florist_v2_products for all to authenticated
  using (public.is_florist_admin())
  with check (public.is_florist_admin());

-- Katalog awal V2 sengaja kosong agar tidak menyalin katalog V1.
-- Transaksi V2 tetap masuk ke florist_orders dan florist_order_items.
-- florist_order_items.product_id akan NULL untuk produk V2; nama/harga
-- disimpan sebagai snapshot sehingga tidak bergantung pada tabel products V1.


-- Pengaturan tampilan V2: wallpaper hero terpisah dari foto produk.
-- Satu baris (id=1) menyimpan wallpaper desktop, mobile, dan tingkat overlay.
create table if not exists public.florist_v2_site_settings (
  id integer primary key check (id = 1),
  hero_desktop_image text not null default '',
  hero_mobile_image text,
  hero_overlay_opacity numeric(3,2) not null default 0.28 check (hero_overlay_opacity >= 0 and hero_overlay_opacity <= 0.70),
  updated_at timestamptz not null default now()
);

alter table public.florist_v2_site_settings enable row level security;
drop policy if exists "Public can read V2 site settings" on public.florist_v2_site_settings;
create policy "Public can read V2 site settings"
  on public.florist_v2_site_settings for select
  using (true);
drop policy if exists "Admins manage V2 site settings" on public.florist_v2_site_settings;
create policy "Admins manage V2 site settings"
  on public.florist_v2_site_settings for all to authenticated
  using (public.is_florist_admin())
  with check (public.is_florist_admin());

insert into public.florist_v2_site_settings (id) values (1)
on conflict (id) do nothing;
